// Generates kollavarsham-astronomy's truncated VSOP87D Earth series (Kotlin source).
//
// Input: the VSOP87D Earth series (Bretagnon & Francou 1988) as packaged, unmodified, in the
// MIT-licensed npm package `astronomia` (data/vsop87Dearth.js). The coefficients are published
// scientific data; this script only selects terms.
//
// Usage: node generate.mjs <path to astronomia/data/vsop87Dearth.js> <output .kt file>
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const [input, output] = process.argv.slice(2);
const series = (await import(pathToFileURL(input).href)).default;

// Amplitude thresholds. L at 1e-8 rad (~0.002") keeps the truncation error far below the 1"
// target; B and R matter only for latitude (< 1.2") and aberration (20.5"/R), so they are cut harder.
const thresholds = { L: 1e-8, B: 1e-7, R: 1e-7 };

let total = 0;
const block = (name) => {
  const powers = Object.keys(series[name]).sort();
  const lines = powers.map((p) => {
    const kept = series[name][p].filter(([a]) => Math.abs(a) >= thresholds[name]);
    total += kept.length;
    const d = (x) => (Number.isInteger(x) ? `${x}.0` : `${x}`);
    const flat = kept.map(([a, b, c]) => `        ${d(a)}, ${d(b)}, ${d(c)},`).join('\n');
    return `    doubleArrayOf(\n${flat}\n    ),`;
  });
  return `internal val VSOP87D_EARTH_${name}: Array<DoubleArray> = arrayOf(\n${lines.join('\n')}\n)\n`;
};

const body = ['L', 'B', 'R'].map(block).join('\n');
const header = `// GENERATED by tools/vsop87-gen/generate.mjs. Do not edit.
//
// VSOP87D Earth series (heliocentric, ecliptic and equinox of date), P. Bretagnon & G. Francou,
// Astronomy & Astrophysics 202, 309 (1988). Truncated at |A| >= ${JSON.stringify(thresholds)}.
// Each array holds one power of tau as consecutive (A, B, C) triples: term = A cos(B + C tau).
@file:Suppress("ktlint")

package io.github.anjalymsajeev.kollavarsham.astronomy

`;
writeFileSync(output, header + body);
console.log(`wrote ${total} terms to ${output}`);
