// Generates kollavarsham-astronomy's lunar periodic terms (Kotlin source).
//
// Input: J. Meeus, Astronomical Algorithms 2nd ed., Tables 47.A and 47.B (abridged ELP-2000/82,
// Chapront), as transcribed in the MIT-licensed npm package `astronomia` (src/moonposition.js).
// The tables are published scientific data; this script only extracts the numbers.
//
// Usage: node generate.mjs <path to astronomia/src/moonposition.js> <output .kt file>
import { readFileSync, writeFileSync } from 'node:fs';

const [input, output] = process.argv.slice(2);
const src = readFileSync(input, 'utf8');

function table(name, columns) {
  const start = src.indexOf(`const ${name} = [`);
  if (start < 0) throw new Error(`table ${name} not found`);
  const end = src.indexOf('\n  ]', start);
  const rows = [...src.slice(start, end).matchAll(/\[([-\d,\s]+)\]/g)]
    .map((m) => m[1].split(',').map((x) => Number(x.trim())));
  rows.forEach((r) => { if (r.length !== columns) throw new Error(`bad row ${r}`); });
  return rows;
}

const a = table('ta', 6); // D, M, M', F, Σl (1e-6 deg), Σr (1e-3 km)
const b = table('tb', 5); // D, M, M', F, Σb (1e-6 deg)
if (a.length !== 60 || b.length !== 60) throw new Error(`expected 60 rows each, got ${a.length}, ${b.length}`);

const fmt = (rows) => rows.map((r) => `        ${r.join(', ')},`).join('\n');
const kt = `// GENERATED by tools/elp-gen/generate.mjs. Do not edit.
//
// Periodic terms of the Moon's longitude, distance (Meeus Table 47.A) and latitude (Table 47.B),
// abridged ELP-2000/82 (M. Chapront-Touzé & J. Chapront). Rows: D, M, M', F, then
// Σl (1e-6 degree) and Σr (1e-3 km) for 47.A, or Σb (1e-6 degree) for 47.B.
@file:Suppress("ktlint")

package io.github.anjalymsajeev.kollavarsham.astronomy

internal val MOON_LONGITUDE_DISTANCE_TERMS: IntArray = intArrayOf(
${fmt(a)}
)

internal val MOON_LATITUDE_TERMS: IntArray = intArrayOf(
${fmt(b)}
)
`;
writeFileSync(output, kt);
console.log(`wrote ${a.length} + ${b.length} lunar terms`);
